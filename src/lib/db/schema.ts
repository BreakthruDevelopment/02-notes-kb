export type NoteChunk = typeof noteChunk.$inferSelect;
export type AiUsage = typeof aiUsage.$inferSelect;
export type AskEvent = typeof askEvent.$inferSelect;
export type RateEvent = typeof rateEvent.$inferSelect;
